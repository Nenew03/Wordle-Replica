// DATA-001 hygiene pass:
// - Normalize to uppercase strings
// - Remove non A–Z / wrong-length entries
// - Remove blocked/offensive/inappropriate entries (answers + valid)
// - Deduplicate while preserving order
// - Ensure answers ⊆ valid for each length
(() => {
  const WORDS = /** @type {any} */ (window).WORDS;
  if (!WORDS || typeof WORDS !== "object") return;

  // DATA-001 curation/profanity filtering:
  // Keep this list small and explicit; expand over time as needed.
  // Notes:
  // - Words are compared AFTER normalization to uppercase.
  // - We filter both answers and valid (recommended), so banned words never appear as guesses.
  const BLOCKED_WORDS = new Set([
    "ASSHOLE",
    "BITCH",
    "JIHAD",
    "PENIS",
    "PORNO",
    "PRICK",
    "WHORE",
  ]);

  // DATA-001 minimum answer counts (matches the targets enforced in test_words.js).
  // If an answers list is underfilled, we top it up from the valid list as an MVP fallback
  // to keep the game playable and keep validation meaningful.
  const MIN_ANSWERS_BY_LENGTH = { 5: 500, 6: 500, 7: 500, 8: 500 };

  /**
   * @param {any} value
   * @param {number} expectedLen
   * @returns {string[]}
   */
  function normalizeList(value, expectedLen) {
    const arr = Array.isArray(value) ? value : [];
    const out = [];
    const seen = new Set();

    for (const raw of arr) {
      const w = String(raw ?? "")
        .trim()
        .toUpperCase();

      if (w.length !== expectedLen) continue;
      if (!/^[A-Z]+$/.test(w)) continue;
      if (BLOCKED_WORDS.has(w)) continue;
      if (seen.has(w)) continue;
      seen.add(w);
      out.push(w);
    }

    return out;
  }

  for (const len of [5, 6, 7, 8]) {
    const bucket = WORDS[len];
    if (!bucket || typeof bucket !== "object") continue;

    let answers = normalizeList(bucket.answers, len);
    const valid = normalizeList(bucket.valid, len);

    // If answers are too small, fill from valid (preserves order: answers first, then valid).
    const minAnswers = MIN_ANSWERS_BY_LENGTH[len] || 0;
    if (minAnswers > 0 && answers.length < minAnswers) {
      const answerSet = new Set(answers);
      for (const w of valid) {
        if (answerSet.size >= minAnswers) break;
        answerSet.add(w);
      }
      answers = Array.from(answerSet);
    }

    // Ensure answers are always allowed guesses too (answers ⊆ valid)
    const validSet = new Set(valid);
    for (const w of answers) validSet.add(w);

    bucket.answers = answers;
    bucket.valid = Array.from(validSet);
  }
})();
